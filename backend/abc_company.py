def _now() -> str:
    return datetime.now().isoformat(sep=" ", timespec="seconds")


def ensure_schema(conn: sqlite3.Connection) -> None:
    conn.executescript(SCHEMA)
    if not conn.execute("SELECT 1 FROM abc_rules LIMIT 1").fetchone():
        for key, rows in DEFAULT_RULES.items():
            for abc_type, value, unit, note in rows:
                source = ("Agri-Stack 360 platform default, chosen by the ABC programme owner"
                          if key in PLATFORM_DEFAULT_KEYS else DRAFT_SOURCE)
                conn.execute("""INSERT INTO abc_rules (key, abc_type, value, unit, effective_from, source,
                                verification_status, note, created_at) VALUES (?,?,?,?,?,?,?,?,?)""",
                             (key, abc_type, value, unit, DRAFT_FROM, source,
                              "platform_default" if key in PLATFORM_DEFAULT_KEYS else PLACEHOLDER, note or None, _now()))
    conn.commit()


# ── Rules ─────────────────────────────────────────────────────────────────────

@dataclass
class Rule:
    key: str
    value: float
    unit: str | None
    abc_type: str
    effective_from: str
    source: str
    verification_status: str
    id: int


def rule(conn: sqlite3.Connection, key: str, abc_type: str = "*", on: date | None = None) -> Rule:
    """The rule in force on `on` (default today): the ABC type's own row if any, else the '*' row."""
    day = (on or date.today()).isoformat()
    row = conn.execute(
        """SELECT id, key, value, unit, abc_type, effective_from, source, verification_status FROM abc_rules
           WHERE key = ? AND abc_type IN (?, '*') AND effective_from <= ?
           ORDER BY (abc_type = '*'), effective_from DESC, id DESC LIMIT 1""", (key, abc_type, day)).fetchone()
    if not row:
        raise KeyError(f"No ABC rule '{key}' in force for type '{abc_type}' on {day}")
    return Rule(key=row[1], value=row[2], unit=row[3], abc_type=row[4], effective_from=row[5], source=row[6],
                verification_status=row[7], id=row[0])


def rules_in_force(conn: sqlite3.Connection, abc_type: str = "*", on: date | None = None) -> list[dict]:
    keys = [r[0] for r in conn.execute("SELECT DISTINCT key FROM abc_rules ORDER BY key")]
    out = []
    for k in keys:
        try:
            out.append(rule(conn, k, abc_type, on).__dict__)
        except KeyError:
            continue
    return out


def add_rule(conn: sqlite3.Connection, user: dict, *, key: str, abc_type: str, value: float, unit: str | None,
             effective_from: date, source: str, verification_status: str, note: str | None) -> dict:
    if abc_type != "*" and abc_type not in ABC_TYPES:
        raise HTTPException(400, f"Unknown ABC type '{abc_type}'.")
    try:
        before = rule(conn, key, abc_type, effective_from).__dict__
    except KeyError:
        before = None
    with conn:
        rid = conn.execute("""INSERT INTO abc_rules (key, abc_type, value, unit, effective_from, source,
                              verification_status, note, created_by, created_at) VALUES (?,?,?,?,?,?,?,?,?,?)""",
                           (key, abc_type, value, unit, effective_from.isoformat(), source, verification_status,
                            note, user["id"], _now())).lastrowid
    after = {"id": rid, "key": key, "abc_type": abc_type, "value": value, "effective_from": effective_from.isoformat(),
             "source": source, "verification_status": verification_status}
    audit.record(conn, actor_id=user["id"], actor_role=user["role"], action="abc.rule.add", target_type="abc_rule",
                 target_id=rid, status=201, detail={"before": before, "after": after})
    return after


# ── Profile ───────────────────────────────────────────────────────────────────

def profile(conn: sqlite3.Connection, org_id: int) -> dict:
    """The ABC's profile row (created with defaults on first use)."""
    conn.execute("INSERT OR IGNORE INTO abc_profiles (org_id, updated_at) VALUES (?, ?)", (org_id, _now()))
    conn.commit()
    cur = conn.execute("SELECT * FROM abc_profiles WHERE org_id = ?", (org_id,))
    return dict(zip([d[0] for d in cur.description], cur.fetchone()))


def update_profile(conn: sqlite3.Connection, user: dict, org_id: int, changes: dict) -> dict:
    before = profile(conn, org_id)
    changes = {k: v for k, v in changes.items() if before.get(k) != v}
    if changes:
        with conn:
            conn.execute(f"UPDATE abc_profiles SET {', '.join(f'{k} = ?' for k in changes)}, updated_at = ? "
                         "WHERE org_id = ?", (*changes.values(), _now(), org_id))
        audit.record(conn, actor_id=user["id"], actor_role=user["role"], action="abc.profile.update",
                     target_type="abc", target_id=org_id, status=200,
                     detail={"before": {k: before.get(k) for k in changes}, "after": changes})
    return profile(conn, org_id)


# ── Roles and access ──────────────────────────────────────────────────────────

def roles_of(conn: sqlite3.Connection, user_id: int) -> dict[int, set[str]]:
    """{org_id: {roles}} for every ABC the user works in (legacy organisation staff = general manager)."""
    out: dict[int, set[str]] = {}
    for org_id, role in conn.execute("""SELECT r.org_id, r.role FROM abc_roles r JOIN organisations o ON o.id = r.org_id
                                        WHERE r.user_id = ? AND o.type = 'abc'""", (user_id,)):
        out.setdefault(org_id, set()).add(role)
    for (org_id,) in conn.execute("""SELECT m.org_id FROM organisation_members m JOIN organisations o ON o.id = m.org_id
                                     JOIN users u ON u.id = m.user_id
                                     WHERE m.user_id = ? AND o.type = 'abc' AND u.role = 'abc_manager'""", (user_id,)):
        out.setdefault(org_id, set()).add("general_manager")
    return out


def my_abcs(conn: sqlite3.Connection, user: dict) -> list[dict]:
    roles = roles_of(conn, user["id"])
    if not roles:
        return []
    marks = ",".join("?" * len(roles))
    rows = conn.execute(f"SELECT id, name, status FROM organisations WHERE id IN ({marks}) ORDER BY name",
                        tuple(roles)).fetchall()
    return [{"org_id": r[0], "name": r[1], "org_status": r[2], "roles": sorted(roles[r[0]])} for r in rows]


@dataclass
class AbcContext:
    org: dict
    profile: dict
    roles: set[str]
    is_admin: bool

    def can(self, capability: str) -> bool:
        return self.is_admin or bool(self.roles & CAPABILITIES[capability])


def abc_for(conn: sqlite3.Connection, user: dict, org_id: int | None, capability: str = "view") -> AbcContext:
    """The ABC this request acts for, if the user holds a role there that allows `capability` (else 403)."""
    is_admin = has_permission(user["role"], P.ORGS_MANAGE)
    roles = roles_of(conn, user["id"])
    if org_id is None:
        if is_admin:
            raise HTTPException(400, "Choose an ABC (org_id).")
        if len(roles) != 1:
            raise HTTPException(400 if roles else 403,
                                "Choose an ABC (org_id)." if roles else "You have no role in an ABC.")
        org_id = next(iter(roles))
    cur = conn.execute("SELECT * FROM organisations WHERE id = ? AND type = 'abc'", (org_id,))
    row = cur.fetchone()
    if not row:
        raise HTTPException(404, "ABC not found")
    org = dict(zip([d[0] for d in cur.description], row))
    ctx = AbcContext(org=org, profile=profile(conn, org_id), roles=roles.get(org_id, set()), is_admin=is_admin)
    if not ctx.is_admin and not ctx.roles:
        raise HTTPException(403, "You have no role in this ABC.")
    if org["status"] != "active" and not is_admin:
        raise HTTPException(403, "This ABC is suspended on the platform.")
    if not ctx.can(capability):
        raise HTTPException(403, f"Your role in this ABC does not allow this ({capability}).")
    return ctx


def team(conn: sqlite3.Connection, org_id: int) -> list[dict]:
    cur = conn.execute("""SELECT r.user_id, u.name, u.phone, u.role AS platform_role, r.role, r.since
                          FROM abc_roles r JOIN users u ON u.id = r.user_id WHERE r.org_id = ?
                          ORDER BY r.role, u.name""", (org_id,))
    cols = [d[0] for d in cur.description]
    return [dict(zip(cols, r)) for r in cur.fetchall()]


def add_role(conn: sqlite3.Connection, ctx: AbcContext, actor: dict, user_id: int, role: str) -> None:
    if role not in ROLES:
        raise HTTPException(400, f"Unknown ABC role '{role}'.")
    if role == "organizing_committee":
        if ctx.profile["status"] != "formation":
            raise HTTPException(400, "The organizing committee is only used while the ABC is being formed.")
        size = conn.execute("SELECT COUNT(*) FROM abc_roles WHERE org_id = ? AND role = 'organizing_committee'",
                            (ctx.org["id"],)).fetchone()[0]
        top = rule(conn, "committee_max", ctx.profile["abc_type"])
        if size >= top.value:
            raise HTTPException(400, f"The organizing committee can have at most {top.value:g} members.")
    with conn:
        conn.execute("INSERT OR IGNORE INTO abc_roles (org_id, user_id, role, since, added_by) VALUES (?,?,?,?,?)",
                     (ctx.org["id"], user_id, role, _now(), actor["id"]))
    audit.record(conn, actor_id=actor["id"], actor_role=actor["role"], action="abc.role.add", target_type="abc",
                 target_id=ctx.org["id"], status=201, detail={"before": None, "after": {"user_id": user_id, "role": role}})


def remove_role(conn: sqlite3.Connection, ctx: AbcContext, actor: dict, user_id: int, role: str) -> None:
    if user_id == actor["id"] and role in CAPABILITIES["team"] and not ctx.is_admin:
        left = conn.execute(f"""SELECT COUNT(*) FROM abc_roles WHERE org_id = ? AND user_id != ?
                                AND role IN ({','.join('?' * len(CAPABILITIES['team']))})""",
                            (ctx.org["id"], user_id, *CAPABILITIES["team"])).fetchone()[0]
        if not left:
            raise HTTPException(400, "Someone else must be able to manage the team before you remove your own role.")
    with conn:
        n = conn.execute("DELETE FROM abc_roles WHERE org_id = ? AND user_id = ? AND role = ?",
                         (ctx.org["id"], user_id, role)).rowcount
    if not n:
        raise HTTPException(404, "That person does not have this role.")
    audit.record(conn, actor_id=actor["id"], actor_role=actor["role"], action="abc.role.remove", target_type="abc",
                 target_id=ctx.org["id"], status=204, detail={"before": {"user_id": user_id, "role": role}, "after": None})


def history(conn: sqlite3.Connection, org_id: int, limit: int = 200) -> list[dict]:
    """Audit entries about this ABC (A1: profile, roles; later milestones add shares, finance, governance)."""
    cur = conn.execute("""SELECT a.id, a.created_at, a.action, a.target_type, a.target_id, a.detail, u.name AS actor
                          FROM audit_log a LEFT JOIN users u ON u.id = a.actor_id
                          WHERE a.action LIKE 'abc.%' AND a.target_type = 'abc' AND a.target_id = ?
                          ORDER BY a.id DESC LIMIT ?""", (str(org_id), limit))
    cols = [d[0] for d in cur.description]
    out = []
    for r in cur.fetchall():
        d = dict(zip(cols, r))
        d["detail"] = json.loads(d["detail"]) if d["detail"] else None
        out.append(d)
    return out
