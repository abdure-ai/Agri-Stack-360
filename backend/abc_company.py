"""
abc_company.py — Farmer Agribusiness Company (ABC) core: profile, legal rules, roles inside an ABC, access.

Spec: docs/agri-stack-abc-module-spec.md; plan: docs/abc-pilot-plan.md (milestone A1).

* Legal numbers (minimum members, share value, ownership cap, ...) are rows in `abc_rules`, never constants in
  code. Each row has an ABC type ('*' = all), an effective date, a source and a verification status. A change
  is a new row with a later effective date, so history stays. The defaults below are the DRAFT figures as
  reported in the spec and are marked PLACEHOLDER_VERIFY until checked against the published law/directive.
* Roles inside an ABC are per organisation (`abc_roles`): one user can be the chair of one ABC and the auditor of
  another, and a farmer can be a board member. The platform role `abc_manager` (organisation staff, M12) counts as
  general manager of their own ABC. Admins (orgs:manage) can act for any ABC.
* The platform keeps support records, not legal documents (OFFICIAL_RECORD_NOTE on every export).
"""

