"""
i18n.py — Fixed advisory messages from reviewed translation files (spec §7).

Safety text, refusals, escalation notices and menus are never generated by the
LLM; they come from data/advisory_i18n/<lang>.json so native speakers can
review them. Missing keys fall back to English. Amharic and Afaan Oromo files
are drafts until reviewed (their _meta.status says so).
"""

from __future__ import annotations

import json
from functools import lru_cache

from backend.advisory.config import EMERGENCY_CONTACT_PLACEHOLDER, HOTLINE_8028, ROOT, env

I18N_DIR = ROOT / "data" / "advisory_i18n"


@lru_cache(maxsize=None)
def _catalog(lang: str) -> dict:
    path = I18N_DIR / f"{lang}.json"
    return json.loads(path.read_text(encoding="utf-8")) if path.exists() else {}


def t(key: str, lang: str = "en", **values) -> str:
    text = _catalog(lang).get(key) or _catalog("en").get(key)
    if text is None:
        raise KeyError(f"Missing advisory message '{key}'")
    defaults = {"hotline": HOTLINE_8028,
                # Until a verified number is set, point to the nearest health centre (no placeholder text shown).
                "emergency_contact": env("ADVISORY_EMERGENCY_CONTACT")
                or _catalog(lang).get("emergency_fallback") or _catalog("en").get("emergency_fallback")
                or EMERGENCY_CONTACT_PLACEHOLDER}
    return text.format(**{**defaults, **values})


def review_status(lang: str) -> str:
    return _catalog(lang).get("_meta", {}).get("status", "missing")
